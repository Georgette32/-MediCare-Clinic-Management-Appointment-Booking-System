using MediCare.Application.Interfaces.Storage;
using Microsoft.Extensions.Options;

namespace MediCare.Infrastructure.Storage;

public sealed class FileStorageOptions
{
    /// <summary>
    /// Folder where uploaded files are kept. When empty, a per-user folder outside the
    /// project is used so medical files are never committed to Git or served as static files.
    /// </summary>
    public string? RootPath { get; set; }
}

public sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(IOptions<FileStorageOptions> options)
    {
        var configured = options.Value.RootPath;

        _root = Path.GetFullPath(
            string.IsNullOrWhiteSpace(configured)
                ? Path.Combine(
                    Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                    "MediCare",
                    "documents")
                : configured);

        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string storedFileName, Stream content, CancellationToken cancellationToken = default)
    {
        var path = ResolvePath(storedFileName);

        await using var file = new FileStream(
            path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);

        await content.CopyToAsync(file, cancellationToken);
    }

    public Task<Stream?> OpenReadAsync(string storedFileName, CancellationToken cancellationToken = default)
    {
        var path = ResolvePath(storedFileName);
        if (!File.Exists(path))
        {
            return Task.FromResult<Stream?>(null);
        }

        Stream stream = new FileStream(
            path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);

        return Task.FromResult<Stream?>(stream);
    }

    public Task DeleteAsync(string storedFileName, CancellationToken cancellationToken = default)
    {
        var path = ResolvePath(storedFileName);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    // Only plain file names generated by the application are accepted, so a stored name
    // can never point outside the storage folder.
    private string ResolvePath(string storedFileName)
    {
        if (string.IsNullOrWhiteSpace(storedFileName) ||
            !string.Equals(Path.GetFileName(storedFileName), storedFileName, StringComparison.Ordinal))
        {
            throw new ArgumentException("The stored file name is not valid.", nameof(storedFileName));
        }

        var fullPath = Path.GetFullPath(Path.Combine(_root, storedFileName));
        if (!fullPath.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new ArgumentException("The stored file name is not valid.", nameof(storedFileName));
        }

        return fullPath;
    }
}
